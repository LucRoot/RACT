"""Package S: the flags the parser accepts, as a table in docs/FLAGS.md.

Sources, read from the parsers themselves (not from the docs):
- every verb's own ``--help`` (``ract <verb> --help``), and the top-level ``ract --help``;
- the headless parser (``ract -p``, ``ract.headless._parser``);
- the two flags ``main`` strips before parsing (``--plain``, ``--no-color``).

``python tests/docs/flags_table.py --write`` regenerates docs/FLAGS.md. Nothing is edited by hand.
"""

from __future__ import annotations

import contextlib
import io
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OPTION = re.compile(r"^\s{1,}(-[^\s].*?)\s{2,}(\S.*)$")
STRIPPED = {
    "--plain": "plain output: labels, no colour, no boxes",
    "--no-color": "no colour",
}


def _help_text(argv: list[str]) -> str:
    from ract import cli

    buf = io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
        try:
            cli.main([*argv, "--help"])
        except SystemExit:
            pass
    return buf.getvalue()


def _options(text: str) -> list[tuple[str, str]]:
    """(flag, first line of help) for each option in an argparse help text.

    An option line starts with two spaces and a dash. Its help follows on the same
    line after a gap of two or more spaces, or on the next indented line when the
    option spec is long.
    """
    rows: list[tuple[str, str]] = []
    in_options = False
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if line.strip() in ("options:", "optional arguments:"):
            in_options = True
            continue
        if line and not line.startswith(" "):
            in_options = False
        if not in_options or not re.match(r"^\s{2}-", line):
            continue
        spec, _, rest = line.strip().partition("  ")
        help_text = rest.strip()
        if (
            not help_text
            and index + 1 < len(lines)
            and lines[index + 1].startswith("      ")
        ):
            help_text = lines[index + 1].strip()
        names = re.findall(r"(--[a-zA-Z][\w-]*)", spec) or re.findall(
            r"(-[a-zA-Z])", spec
        )
        for name in names:
            rows.append((name, help_text))
    return rows


def _subcommands(text: str) -> list[str]:
    """The subcommand names listed under a verb's "positional arguments" section."""
    names: list[str] = []
    in_positional = False
    for line in text.splitlines():
        if line.strip() == "positional arguments:":
            in_positional = True
            continue
        if line and not line.startswith(" "):
            in_positional = False
        if in_positional:
            match = re.match(r"^\s+\{([a-z][\w,-]*)\}", line)
            if match:
                names.extend(part for part in match.group(1).split(",") if part)
    return names


def collect() -> list[tuple[str, str, str]]:
    """(flag, where, help) for every flag the parsers accept, sorted and de-duplicated."""
    from ract import cli, headless

    # Help text wraps at the terminal width; pin it so the table is the same on every run.
    os.environ["COLUMNS"] = "200"
    seen: dict[str, tuple[str, str]] = {}

    def add(where: str, rows: list[tuple[str, str]]) -> None:
        for flag, help_text in rows:
            seen.setdefault(flag, (where, help_text))

    add("ract", _options(_help_text([])))
    for verb in sorted(cli.CLI_VERBS):
        verb_help = _help_text([verb])
        add(f"ract {verb}", _options(verb_help))
        for sub in _subcommands(verb_help):
            add(f"ract {verb} {sub}", _options(_help_text([verb, sub])))
    headless_help = headless._parser().format_help()
    add("ract -p", _options(headless_help))
    for flag, help_text in STRIPPED.items():
        seen.setdefault(flag, ("ract (any command)", help_text))
    return sorted((flag, where, help_text) for flag, (where, help_text) in seen.items())


def render(rows: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Flags",
        "",
        "Generated by `tests/docs/flags_table.py` from the parsers themselves. Do not edit by hand.",
        "Each flag is listed once, with the first command that accepts it and the first line of its help.",
        "",
        "| Flag | Accepted by | What it does |",
        "| --- | --- | --- |",
    ]
    for flag, where, help_text in rows:
        cell = help_text.replace("|", "\|") or "-"
        lines.append(f"| `{flag}` | `{where}` | {cell} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if argv != ["--write"]:
        print("usage: python tests/docs/flags_table.py --write")
        return 2
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("COLUMNS", "120")
    text = render(collect())
    (ROOT / "docs" / "FLAGS.md").write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote docs/FLAGS.md ({text.count(chr(10)) - 6} flags)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
