"""Leaderboard regenerator — module_07 (v0.4.0 substrate + ALM).

Reads the most recent report per (provider, corpus) under
``evals/runs/`` and regenerates ``evals/LEADERBOARD.md`` with a
stable-ordered table. The script is idempotent — running it without
new reports leaves the file byte-identical, so a no-op nightly run
produces no commit (Lateral Chain branch D, substrate module_07).

Columns (v0.4.0 ALM module_07 shape):

- provider
- Aider Polyglot subset (X of 10) — from
  ``<date>-polyglot-<provider>.json``.
- SWE-bench Lite (X of 5) — from
  ``<date>-swebench_lite-<provider>.json``.
- Conformance pass rate — from ``evals/conformance/RESULTS.md``
  (module_04). If the file does not exist, the column reads ``-``.
- Security pass rate — from ``evals/runs/security/RESULTS.md``
  (module_03). If the file does not exist, the column reads ``-``.
- ``claimed_pass_rate`` — the pass rate reported by the run itself
  (numerator = passed, denominator = passed + failed + skipped, i.e.
  subset_size). Historical shape from substrate.
- ``attested_pass_rate`` — the fraction of runs whose rootknot
  metadata verifies under all three signatures (RK-1 generator,
  RK-3 environment, AL-1 anti-lazy) with ``reversal_taint == "clean"``
  and every gate PASS or resolved. Reads from
  ``evals/runs/*/rootknot.json`` (per-run rootknot sidecar summary).
  Runs with no rootknot file (e.g., the run crashed before rootknot
  generation) are EXCLUDED from BOTH numerator and denominator — an
  honest reflection of what can and cannot be measured (ALM module_07
  Second Pass Q2 answer).
- ``attestation_gap`` — ``claimed - attested`` (clamped to zero-or-
  positive). A large gap is a provider signal (reward-hacking rate);
  a small gap under 0.05 is measurement noise (Lateral Chain branch C).
- Last-updated date — max ``generated_on`` across the row's reports.

Lateral Chain branch E: the leaderboard reads module-internal
RESULTS.md files rather than duplicating their content.
"""

