CORPUS_POLYGLOT = "polyglot"
CORPUS_SWEBENCH = "swebench_lite"


# ---------------------------------------------------------------------------
# Report loading
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class CorpusRow:
    """One (provider, corpus) cell — the source of truth for the table."""

    provider: str
    corpus: str
    passed: int
    subset_size: int
    scored: int
    generated_on: str


def _iter_report_files(runs_root: Path) -> list[Path]:
    """Return every ``*-<corpus>-<provider>.json`` under ``runs_root``.

    Also descends one level into ``runs_root``'s subdirectories so the
    ALM ``polyglot_antilazy`` / ``swe_bench_lite_antilazy`` /
    ``security_antilazy`` rerun corpora surface (module_07 step 5).
    """
    if not runs_root.is_dir():
        return []
    files: list[Path] = []
    candidates: list[Path] = list(runs_root.glob("*.json"))
    for sub in sorted(runs_root.iterdir()):
        if sub.is_dir():
            candidates.extend(sub.glob("*.json"))
    for path in sorted(candidates):
        # Only accept files that look like the report shape (name-
        # matched). Older v0.3 run artifacts under runs/ do not match.
        if re.match(
            r"^\d{4}-\d{2}-\d{2}-(polyglot|swebench_lite)-[a-zA-Z0-9_.-]+\.json$",
            path.name,
        ):
            files.append(path)
    return files


def _load_report(path: Path) -> CorpusRow | None:
    """Parse one report JSON into a ``CorpusRow`` (or ``None`` on shape drift)."""
    try:
        data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None
    corpus = data.get("corpus")
    provider = data.get("provider")
    if corpus not in {"aider_polyglot", "swebench_lite"}:
        return None
    if not isinstance(provider, str):
        return None
    normalized_corpus = (
        CORPUS_POLYGLOT if corpus == "aider_polyglot" else CORPUS_SWEBENCH
    )
    return CorpusRow(
        provider=provider,
        corpus=normalized_corpus,
        passed=int(data.get("passed", 0)),
        subset_size=int(data.get("subset_size", 0)),
        scored=int(data.get("passed", 0)) + int(data.get("failed", 0)),
        generated_on=str(data.get("generated_on", "")),
    )


def _latest_per_provider(rows: list[CorpusRow]) -> dict[tuple[str, str], CorpusRow]:
    """Reduce rows to the newest per ``(provider, corpus)`` tuple."""
    latest: dict[tuple[str, str], CorpusRow] = {}
    for row in rows:
        key = (row.provider, row.corpus)
        prev = latest.get(key)
        if prev is None or row.generated_on > prev.generated_on:
            latest[key] = row
    return latest


# ---------------------------------------------------------------------------
# Conformance / security cell readers (module_03 / module_04)
# ---------------------------------------------------------------------------


def _read_conformance_pass_rate(conformance_results: Path) -> str:
    """Return a human-readable conformance pass rate cell, or ``-``.

    The reader parses ``evals/conformance/RESULTS.md`` for a line of
    the form ``* provider=<name> overall_pass_rate=<float>``. If the
    file is missing or unparseable, returns ``-``.
    """
    if not conformance_results.is_file():
        return "-"
    text = conformance_results.read_text(encoding="utf-8")
    match = re.search(r"overall_pass_rate\s*=\s*([0-9.]+)", text)
    if match:
        try:
            return f"{float(match.group(1)):.1%}"
        except ValueError:
            return "-"
    return "-"


def _read_security_pass_rate(security_results: Path) -> str:
    """Return a human-readable security pass rate cell, or ``-``."""
    if not security_results.is_file():
        return "-"
    text = security_results.read_text(encoding="utf-8")
    match = re.search(r"overall_pass_rate\s*=\s*([0-9.]+)", text)
    if match:
        try:
            return f"{float(match.group(1)):.1%}"
        except ValueError:
            return "-"
    return "-"


# ---------------------------------------------------------------------------
# ALM module_07 — attested_pass_rate + attestation_gap
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class AttestationSummary:
    """Per-provider attestation summary computed from rootknot sidecars."""

    provider: str
    total_runs_with_rootknot: int
    attested_runs: int
    total_runs_no_rootknot: int  # excluded from both numerator and denominator


def _iter_rootknot_files(runs_root: Path) -> list[Path]:
    """Return every ``rootknot.json`` under ``runs_root`` (recursive).

    ALM module_07 stores per-run rootknot summaries at
    ``evals/runs/<corpus>/<run-id>/rootknot.json``. The reader is
    permissive: any file whose name is exactly ``rootknot.json`` is
    considered a candidate.
    """
    if not runs_root.is_dir():
        return []
    return sorted(runs_root.rglob("rootknot.json"))


def _classify_rootknot(path: Path) -> tuple[str | None, bool]:
    """Return ``(provider, is_attested)`` for one rootknot sidecar.

    ``is_attested`` iff (RK-1 valid) AND (RK-3 valid) AND (AL-1 valid)
    AND (``reversal_taint == "clean"``) AND (every gate PASS or
    handshake-resolved). Missing keys are treated as False.
    """
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None, False
    provider = data.get("provider")
    if not isinstance(provider, str):
        return None, False

    signatures = data.get("signatures") if isinstance(data.get("signatures"), dict) else {}
    rk1 = bool(signatures.get("generator_valid", False))
    rk3 = bool(signatures.get("environment_valid", False))
    al1 = bool(signatures.get("antilazy_valid", False))
    taint = data.get("reversal_taint", "partial")
    taint_clean = taint == "clean"

    gate_results = data.get("gate_results")
    all_gates_ok = True
    if isinstance(gate_results, list):
        for gr in gate_results:
            if not isinstance(gr, dict):
                all_gates_ok = False
                break
            passed = bool(gr.get("passed", False))
            handshake = gr.get("handshake_id")
            if not passed and not handshake:
                all_gates_ok = False
                break
    elif isinstance(gate_results, dict):
        for _, gr in gate_results.items():
            if not isinstance(gr, dict):
                all_gates_ok = False
                break
            passed = bool(gr.get("passed", False))
            handshake = gr.get("handshake_id")
            if not passed and not handshake:
                all_gates_ok = False
                break
    else:
        all_gates_ok = False

    return provider, (rk1 and rk3 and al1 and taint_clean and all_gates_ok)


def compute_attestation_summaries(runs_root: Path) -> dict[str, AttestationSummary]:
    """Return per-provider ``AttestationSummary`` computed from rootknot sidecars.

    Runs with no rootknot file are counted separately in
    ``total_runs_no_rootknot`` and excluded from both numerator and
    denominator of ``attested_pass_rate`` (ALM module_07 Second Pass
    Q2 answer; ADR-0025 rationale).
    """
    summaries: dict[str, AttestationSummary] = {}

    for path in _iter_rootknot_files(runs_root):
        provider, attested = _classify_rootknot(path)
        if provider is None:
            continue
        prev = summaries.get(provider)
        if prev is None:
            prev = AttestationSummary(
                provider=provider,
                total_runs_with_rootknot=0,
                attested_runs=0,
                total_runs_no_rootknot=0,
            )
        summaries[provider] = AttestationSummary(
            provider=provider,
            total_runs_with_rootknot=prev.total_runs_with_rootknot + 1,
            attested_runs=prev.attested_runs + (1 if attested else 0),
            total_runs_no_rootknot=prev.total_runs_no_rootknot,
        )

    # Also count "crashed" runs (per-corpus manifest listing a run
    # that has no rootknot.json). Convention: any per-corpus subdir
    # with a MISSING_ROOTKNOT.txt marker file counts as one such run
    # per line in that file. Absent-file case is normal (no crashes
    # to report).
    for marker in runs_root.rglob("MISSING_ROOTKNOT.txt"):
        try:
            lines = [ln for ln in marker.read_text(encoding="utf-8").splitlines() if ln.strip()]
        except OSError:
            continue
        for line in lines:
            parts = line.split(None, 1)
            if not parts:
                continue
            provider = parts[0]
            prev = summaries.get(provider)
            if prev is None:
                prev = AttestationSummary(
                    provider=provider,
                    total_runs_with_rootknot=0,
                    attested_runs=0,
                    total_runs_no_rootknot=0,
                )
            summaries[provider] = AttestationSummary(
                provider=provider,
                total_runs_with_rootknot=prev.total_runs_with_rootknot,
                attested_runs=prev.attested_runs,
                total_runs_no_rootknot=prev.total_runs_no_rootknot + 1,
            )

    return summaries


def _attested_cell(summary: AttestationSummary | None) -> str:
    """Return the ``attested_pass_rate`` cell for the summary, or ``-``."""
    if summary is None or summary.total_runs_with_rootknot == 0:
        return "-"
    return f"{summary.attested_runs / summary.total_runs_with_rootknot:.1%}"


def _attested_ratio(summary: AttestationSummary | None) -> float | None:
    """Return the numeric attested ratio, or ``None`` when undefined."""
    if summary is None or summary.total_runs_with_rootknot == 0:
        return None
    return summary.attested_runs / summary.total_runs_with_rootknot


def _claimed_ratio_for_provider(
    latest: dict[tuple[str, str], CorpusRow], provider: str
) -> float | None:
    """Return the claimed pass rate averaged across a provider's corpora.

    Averages ``passed / subset_size`` across whichever corpora have a
    row for the provider. Returns ``None`` when the provider has no
    corpus rows (nothing to claim).
    """
    ratios: list[float] = []
    for corpus in (CORPUS_POLYGLOT, CORPUS_SWEBENCH):
        row = latest.get((provider, corpus))
        if row is None or row.subset_size == 0:
            continue
        ratios.append(row.passed / row.subset_size)
    if not ratios:
        return None
    return sum(ratios) / len(ratios)


def _claimed_cell(ratio: float | None) -> str:
    if ratio is None:
        return "-"
    return f"{ratio:.1%}"


def _gap_cell(claimed: float | None, attested: float | None) -> str:
    if claimed is None or attested is None:
        return "-"
    gap = max(0.0, claimed - attested)
    return f"{gap:.1%}"


# ---------------------------------------------------------------------------
# Table rendering
# ---------------------------------------------------------------------------


@dataclass
class LeaderboardTable:
    """Rendered leaderboard table plus the providers it covers."""

    markdown: str
    provider_count: int


def _cell_for(row: CorpusRow | None) -> str:
    if row is None:
        return "-"
    return f"{row.passed} of {row.subset_size}"


def _last_updated_for(rows: list[CorpusRow | None]) -> str:
    """Return the max ``generated_on`` across a row's cells, or ``-``."""
    dates = [r.generated_on for r in rows if r is not None and r.generated_on]
    return max(dates) if dates else "-"


def render_leaderboard(
    runs_root: Path,
    conformance_results: Path,
    security_results: Path,
) -> LeaderboardTable:
    """Render the leaderboard body from the reports on disk.

    The result excludes the outer ``LEADERBOARD_HEADER`` /
    ``LEADERBOARD_FOOTER`` wrappers; ``write_leaderboard`` stitches
    them together.
    """
    reports = [r for r in (_load_report(p) for p in _iter_report_files(runs_root)) if r]
    latest = _latest_per_provider(reports)
    attestations = compute_attestation_summaries(runs_root)
    providers = sorted({key[0] for key in latest} | set(attestations.keys()))

    conformance_cell = _read_conformance_pass_rate(conformance_results)
    security_cell = _read_security_pass_rate(security_results)

    lines = [
        "| Provider | Aider Polyglot (10) | SWE-bench Lite (5) | Conformance | Security | claimed_pass_rate | attested_pass_rate | attestation_gap | Last updated |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for provider in providers:
        poly = latest.get((provider, CORPUS_POLYGLOT))
        sweb = latest.get((provider, CORPUS_SWEBENCH))
        summary = attestations.get(provider)
        last_updated = _last_updated_for([poly, sweb])
        claimed = _claimed_ratio_for_provider(latest, provider)
        attested = _attested_ratio(summary)
        lines.append(
            f"| `{provider}` | {_cell_for(poly)} | {_cell_for(sweb)} | "
            f"{conformance_cell} | {security_cell} | "
            f"{_claimed_cell(claimed)} | {_attested_cell(summary)} | "
            f"{_gap_cell(claimed, attested)} | {last_updated} |"
        )
    if not providers:
        lines.append(
            "| _no reports yet_ | - | - | - | - | - | - | - | - |"
        )
    return LeaderboardTable(
        markdown="\n".join(lines) + "\n", provider_count=len(providers)
    )


def render_full_document(table: LeaderboardTable) -> str:
    """Stitch header + table + footer into the full leaderboard file."""
    return LEADERBOARD_HEADER + table.markdown + LEADERBOARD_FOOTER


# ---------------------------------------------------------------------------
# Idempotent file writer
# ---------------------------------------------------------------------------


@dataclass
class UpdateOutcome:
    """Result of an ``update`` call."""

    written: bool
    path: Path
    provider_count: int


def update(
    leaderboard_path: Path,
    runs_root: Path,
    conformance_results: Path,
    security_results: Path,
) -> UpdateOutcome:
    """Regenerate the leaderboard file. Idempotent — no write on no-op."""
    table = render_leaderboard(runs_root, conformance_results, security_results)
    new_document = render_full_document(table)
    if leaderboard_path.is_file():
        current = leaderboard_path.read_text(encoding="utf-8")
        if current == new_document:
            return UpdateOutcome(
                written=False,
                path=leaderboard_path,
                provider_count=table.provider_count,
            )
    leaderboard_path.parent.mkdir(parents=True, exist_ok=True)
    leaderboard_path.write_text(new_document, encoding="utf-8")
    return UpdateOutcome(
        written=True,
        path=leaderboard_path,
        provider_count=table.provider_count,
    )


# ---------------------------------------------------------------------------
# CLI entry
# ---------------------------------------------------------------------------


def _main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate evals/LEADERBOARD.md (idempotent)."
    )
    parser.add_argument("--repo-root", default=".", type=Path)
    args = parser.parse_args(argv)
    repo_root: Path = args.repo_root
    outcome = update(
        leaderboard_path=repo_root / "evals" / "LEADERBOARD.md",
        runs_root=repo_root / "evals" / "runs",
        conformance_results=repo_root / "evals" / "conformance" / "RESULTS.md",
        security_results=repo_root / "evals" / "runs" / "security" / "RESULTS.md",
    )
    print(
        json.dumps(
            {
                "written": outcome.written,
                "path": str(outcome.path),
                "provider_count": outcome.provider_count,
            }
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(_main())


